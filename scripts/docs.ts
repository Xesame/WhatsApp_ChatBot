/**
 * Generates the reference docs that must never drift from the code:
 *
 *   docs/generated/env.md       environment variables, from @reb/config
 *   .env.example                 the same variables, ready to copy to .env
 *   docs/generated/template.md   the 26 Primary Units columns and their rules, from @reb/schema
 *   docs/generated/database.md   tables and columns, from the Drizzle schema
 *                                and the descriptions in packages/db/src/schema/docs.ts
 *   docs/generated/api.md        every API route, from the Fastify route schemas
 *
 * Usage:
 *   pnpm run docs      regenerate the files
 *   pnpm docs:check    exit with an error if any file is out of date (CI runs this)
 *
 * (`pnpm docs` without `run` is a built-in pnpm command that opens a
 * package's homepage, so the `run` is required.)
 * */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { composeEnvSchema, envSchema } from '@reb/config';
import * as db from '@reb/db';
import { TEMPLATE_COLUMNS } from '@reb/schema';
import { getTableConfig, PgTable } from 'drizzle-orm/pg-core';
import { z } from 'zod';
import { openApiDocument } from '../apps/api/src/openapi.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const GENERATED_NOTE = 'Generated by `pnpm run docs`. Do not edit by hand.';

interface JsonSchemaProperty {
  type?: string;
  enum?: string[];
  description?: string;
  default?: string | number | boolean;
  examples?: (string | number)[];
  secret?: boolean;
  usedBy?: string;
  requiredFor?: string[];
}

interface EnvVarDoc {
  name: string;
  description: string;
  /** "yes", "no", or the services that require it (e.g. "capture") */
  required: string;
  defaultValue: string;
  example: string;
  secret: boolean;
  allowed: string;
  usedBy: string;
}

function describeEnv(schema: z.ZodObject): EnvVarDoc[] {
  const json = z.toJSONSchema(schema, { io: 'input' }) as {
    properties: Record<string, JsonSchemaProperty>;
    required?: string[];
  };
  return Object.entries(json.properties).map(([name, property]) => {
    if (!property.description || !property.usedBy) {
      throw new Error(`Env var ${name} needs a description and usedBy in .meta()`);
    }
    return {
      name,
      description: property.description,
      required: json.required?.includes(name) ? 'yes' : (property.requiredFor?.join(', ') ?? 'no'),
      // Defaults that are absolute paths are shown relative to the repository,
      // so the generated docs are identical on every machine.
      defaultValue:
        property.default === undefined ? '' : String(property.default).replace(root, '<repo>/'),
      example: property.examples?.[0] === undefined ? '' : String(property.examples[0]),
      secret: property.secret === true,
      allowed: property.enum ? property.enum.map((v) => `\`${v}\``).join(', ') : '',
      usedBy: property.usedBy,
    };
  });
}

const envVars = [...describeEnv(envSchema), ...describeEnv(composeEnvSchema)];

const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

function renderEnvMarkdown(): string {
  const rows = envVars.map((v) =>
    [
      `\`${v.name}\``,
      v.required,
      v.defaultValue ? `\`${v.defaultValue}\`` : '',
      v.example ? `\`${v.example}\`` : '',
      cell(v.description) +
        (v.allowed ? ` Allowed: ${v.allowed}.` : '') +
        (v.secret ? ' **Secret.**' : ''),
      v.usedBy,
    ].join(' | '),
  );
  return [
    '# Environment variables',
    '',
    `<!-- ${GENERATED_NOTE} Source: packages/config/src/env.ts -->`,
    '',
    'Copy `.env.example` to `.env` and fill in the values. Variables marked **Secret** must never be committed or shared.',
    '',
    '| Variable | Required | Default | Example | Purpose | Used by |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row} |`),
    '',
  ].join('\n');
}

function renderEnvExample(): string {
  const lines = [`# ${GENERATED_NOTE}`, '# Copy to .env and change every secret value.', ''];
  for (const v of envVars) {
    lines.push(`# ${v.description}`);
    const requirement =
      v.required === 'yes'
        ? 'Required'
        : v.required === 'no'
          ? `Optional, default: ${v.defaultValue || '(none)'}`
          : `Required for ${v.required}`;
    lines.push(`# ${requirement}. Used by: ${v.usedBy}.`);
    lines.push(`${v.name}=${v.example}`, '');
  }
  return lines.join('\n');
}

function renderDatabaseMarkdown(): string {
  const tables = (Object.values(db) as unknown[])
    .filter((value): value is PgTable => value instanceof PgTable)
    .map((table) => getTableConfig(table));

  const sections: string[] = [];
  const relations: string[] = [];
  const entities: string[] = [];

  for (const table of tables) {
    const docs = db.tableDocs[table.name];
    if (!docs)
      throw new Error(`Table ${table.name} is missing from packages/db/src/schema/docs.ts`);

    const fkByColumn = new Map<string, string>();
    for (const fk of table.foreignKeys) {
      const ref = fk.reference();
      const target = getTableConfig(ref.foreignTable).name;
      for (const column of ref.columns) {
        fkByColumn.set(column.name, `${target}.${ref.foreignColumns[0]?.name ?? 'id'}`);
      }
      relations.push(
        `  ${target} ||--o{ ${table.name} : "${ref.columns.map((c) => c.name).join(', ')}"`,
      );
    }

    const rows = table.columns.map((column) => {
      const description = docs.columns[column.name];
      if (!description) {
        throw new Error(
          `Column ${table.name}.${column.name} is missing from packages/db/src/schema/docs.ts`,
        );
      }
      const notes = [
        column.primary ? 'primary key' : '',
        column.isUnique ? 'unique' : '',
        fkByColumn.has(column.name) ? `→ ${fkByColumn.get(column.name) ?? ''}` : '',
      ]
        .filter(Boolean)
        .join(', ');
      return `| \`${column.name}\` | ${column.getSQLType()} | ${column.notNull ? 'no' : 'yes'} | ${notes} | ${cell(description)} |`;
    });

    const extra = docs.columns;
    for (const name of Object.keys(extra)) {
      if (!table.columns.some((c) => c.name === name)) {
        throw new Error(`docs.ts documents ${table.name}.${name}, which does not exist`);
      }
    }

    const constraints = [
      ...table.indexes.map((index) => {
        const config = index.config;
        const columns = config.columns.map((c) => ('name' in c ? c.name : 'expression')).join(', ');
        return `- ${config.unique ? 'Unique index' : 'Index'} \`${config.name ?? ''}\` on (${columns})${config.method && config.method !== 'btree' ? ` using ${config.method}` : ''}`;
      }),
      ...table.checks.map((c) => `- Check \`${c.name}\``),
    ];

    entities.push(
      `  ${table.name} {`,
      ...table.columns.map(
        (c) =>
          `    ${c.getSQLType().replaceAll(' ', '_')} ${c.name}${c.primary ? ' PK' : fkByColumn.has(c.name) ? ' FK' : ''}`,
      ),
      '  }',
    );

    sections.push(
      `## \`${table.name}\``,
      '',
      docs.description,
      '',
      '| Column | Type | Nullable | Keys | Meaning |',
      '| --- | --- | --- | --- | --- |',
      ...rows,
      '',
      ...(constraints.length ? ['**Indexes and constraints**', '', ...constraints, ''] : []),
    );
  }

  return [
    '# Database reference',
    '',
    `<!-- ${GENERATED_NOTE} Sources: packages/db/src/schema/ -->`,
    '',
    '```mermaid',
    'erDiagram',
    ...relations,
    ...entities,
    '```',
    '',
    ...sections,
  ].join('\n');
}

function renderTemplateMarkdown(): string {
  return [
    '# Primary Units template',
    '',
    `<!-- ${GENERATED_NOTE} Source: packages/schema/src/columns.ts -->`,
    '',
    'The 26 export columns in order, the database column behind each, and how its value is produced. The model only copies phrases; every rule below runs in code.',
    '',
    '| # | Template header | Database column | Rule |',
    '| --- | --- | --- | --- |',
    ...TEMPLATE_COLUMNS.map(
      (c, i) => `| ${i + 1} | ${c.header} | \`${c.dbColumn}\` | ${cell(c.rule)} |`,
    ),
    '',
  ].join('\n');
}

interface OpenApiSchema {
  type?: string | string[];
  enum?: unknown[];
  format?: string;
  anyOf?: OpenApiSchema[];
  items?: OpenApiSchema;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number | boolean;
  default?: unknown;
  properties?: Record<string, OpenApiSchema>;
  required?: string[];
}
interface OpenApiOperation {
  summary?: string;
  tags?: string[];
  parameters?: { in: string; name: string; required?: boolean; schema?: OpenApiSchema }[];
  requestBody?: { content?: Record<string, { schema?: OpenApiSchema }> };
}

function typeOf(schema: OpenApiSchema | undefined): string {
  if (!schema) return '';
  if (schema.enum) return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' / ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  if (schema.type === 'array') return `list of ${typeOf(schema.items)}`;
  const base = Array.isArray(schema.type) ? schema.type.join(' or ') : (schema.type ?? 'any');
  // OpenAPI 3.0 writes "greater than 0" as minimum 0 + exclusiveMinimum true
  const low =
    schema.exclusiveMinimum === true && schema.minimum === 0
      ? schema.type === 'integer'
        ? 1
        : 'above 0, '
      : typeof schema.exclusiveMinimum === 'number'
        ? schema.exclusiveMinimum
        : schema.minimum;
  const high = schema.maximum === Number.MAX_SAFE_INTEGER ? undefined : schema.maximum;
  const range = [low, high];
  const bounds =
    range[0] !== undefined || range[1] !== undefined
      ? ` (${String(range[0] ?? '…')}${typeof range[0] === 'string' ? `up to ${String(range[1] ?? '…')}` : `–${String(range[1] ?? '…')}`})`
      : '';
  return `${base}${schema.format ? ` (${schema.format})` : ''}${bounds}`;
}

async function renderApiMarkdown(): Promise<string> {
  const document = (await openApiDocument()) as {
    paths: Record<string, Record<string, OpenApiOperation>>;
  };
  const lines = [
    '# API reference',
    '',
    GENERATED_NOTE,
    '',
    'Every `/api/admin` route needs a signed-in owner (session cookie from `/api/auth/sign-in/email`) and answers 401 otherwise. Requests that change something are refused (403) when they come from a page other than `PUBLIC_URL`. Every change is written to `audit_log`.',
    '',
    'Sign-in, sign-out and session routes under `/api/auth/*` are served by [Better Auth](https://www.better-auth.com/docs/api-reference) (email and password; public sign-up is off, the owner is created with `pnpm --filter @reb/api create-owner`).',
    '',
  ];
  const byTag = new Map<string, string[]>();
  for (const [path, methods] of Object.entries(document.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      const tag = op.tags?.[0] ?? 'Other';
      const section = byTag.get(tag) ?? [];
      section.push(`### \`${method.toUpperCase()} ${path}\``, '', op.summary ?? '', '');
      const rows: string[] = [];
      for (const p of op.parameters ?? []) {
        rows.push(
          `| ${p.in === 'path' ? 'path' : 'query'} | \`${p.name}\` | ${typeOf(p.schema)} | ${p.required ? 'yes' : 'no'} |`,
        );
      }
      const body = op.requestBody?.content?.['application/json']?.schema;
      for (const [name, prop] of Object.entries(body?.properties ?? {})) {
        rows.push(
          `| body | \`${name}\` | ${typeOf(prop)} | ${body?.required?.includes(name) ? 'yes' : 'no'} |`,
        );
      }
      if (rows.length > 0) {
        section.push('| In | Name | Type | Required |', '| --- | --- | --- | --- |', ...rows, '');
      }
      byTag.set(tag, section);
    }
  }
  for (const [tag, section] of byTag) {
    lines.push(`## ${tag}`, '', ...section);
  }
  return `${lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`;
}

const outputs: Record<string, string> = {
  'docs/generated/api.md': await renderApiMarkdown(),
  'docs/generated/env.md': renderEnvMarkdown(),
  '.env.example': renderEnvExample(),
  'docs/generated/database.md': renderDatabaseMarkdown(),
  'docs/generated/template.md': renderTemplateMarkdown(),
};

const check = process.argv.includes('--check');
const stale: string[] = [];
for (const [path, content] of Object.entries(outputs)) {
  const fullPath = `${root}${path}`;
  if (check) {
    const current = await readFile(fullPath, 'utf8').catch(() => '');
    if (current !== content) stale.push(path);
  } else {
    await writeFile(fullPath, content);
    console.log(`wrote ${path}`);
  }
}
if (stale.length > 0) {
  console.error(`Out of date: ${stale.join(', ')}. Run \`pnpm docs\` and commit the result.`);
  process.exit(1);
}
if (check) console.log('Generated docs are up to date.');
