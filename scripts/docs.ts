/**
 * Generates the reference docs that must never drift from the code:
 *
 *   docs/generated/env.md       environment variables, from @reb/config
 *   .env.example                 the same variables, ready to copy to .env
 *   docs/generated/database.md   tables and columns, from the Drizzle schema
 *                                and the descriptions in packages/db/src/schema/docs.ts
 *
 * Usage:
 *   pnpm run docs      regenerate the files
 *   pnpm docs:check    exit with an error if any file is out of date (CI runs this)
 *
 * (`pnpm docs` without `run` is a built-in pnpm command that opens a
 * package's homepage, so the `run` is required.)
 *
 * The API reference (from Fastify route schemas) joins this script in Phase 5.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { composeEnvSchema, envSchema } from '@reb/config';
import * as db from '@reb/db';
import { getTableConfig, PgTable } from 'drizzle-orm/pg-core';
import { z } from 'zod';

const root = fileURLToPath(new URL('..', import.meta.url));
const GENERATED_NOTE = 'Generated by `pnpm run docs`. Do not edit by hand.';

interface JsonSchemaProperty {
  type?: string;
  enum?: string[];
  description?: string;
  default?: string | number | boolean;
  examples?: (string | number)[];
  secret?: boolean;
  usedBy?: string;
}

interface EnvVarDoc {
  name: string;
  description: string;
  required: boolean;
  defaultValue: string;
  example: string;
  secret: boolean;
  allowed: string;
  usedBy: string;
}

function describeEnv(schema: z.ZodObject): EnvVarDoc[] {
  const json = z.toJSONSchema(schema, { io: 'input' }) as {
    properties: Record<string, JsonSchemaProperty>;
    required?: string[];
  };
  return Object.entries(json.properties).map(([name, property]) => {
    if (!property.description || !property.usedBy) {
      throw new Error(`Env var ${name} needs a description and usedBy in .meta()`);
    }
    return {
      name,
      description: property.description,
      required: json.required?.includes(name) ?? false,
      defaultValue: property.default === undefined ? '' : String(property.default),
      example: property.examples?.[0] === undefined ? '' : String(property.examples[0]),
      secret: property.secret === true,
      allowed: property.enum ? property.enum.map((v) => `\`${v}\``).join(', ') : '',
      usedBy: property.usedBy,
    };
  });
}

const envVars = [...describeEnv(envSchema), ...describeEnv(composeEnvSchema)];

const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

function renderEnvMarkdown(): string {
  const rows = envVars.map((v) =>
    [
      `\`${v.name}\``,
      v.required ? 'yes' : 'no',
      v.defaultValue ? `\`${v.defaultValue}\`` : '',
      v.example ? `\`${v.example}\`` : '',
      cell(v.description) +
        (v.allowed ? ` Allowed: ${v.allowed}.` : '') +
        (v.secret ? ' **Secret.**' : ''),
      v.usedBy,
    ].join(' | '),
  );
  return [
    '# Environment variables',
    '',
    `<!-- ${GENERATED_NOTE} Source: packages/config/src/env.ts -->`,
    '',
    'Copy `.env.example` to `.env` and fill in the values. Variables marked **Secret** must never be committed or shared.',
    '',
    '| Variable | Required | Default | Example | Purpose | Used by |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row} |`),
    '',
  ].join('\n');
}

function renderEnvExample(): string {
  const lines = [`# ${GENERATED_NOTE}`, '# Copy to .env and change every secret value.', ''];
  for (const v of envVars) {
    lines.push(`# ${v.description}`);
    lines.push(
      `# ${v.required ? 'Required' : `Optional, default: ${v.defaultValue}`}. Used by: ${v.usedBy}.`,
    );
    lines.push(`${v.name}=${v.example}`, '');
  }
  return lines.join('\n');
}

function renderDatabaseMarkdown(): string {
  const tables = (Object.values(db) as unknown[])
    .filter((value): value is PgTable => value instanceof PgTable)
    .map((table) => getTableConfig(table));

  const sections: string[] = [];
  const relations: string[] = [];
  const entities: string[] = [];

  for (const table of tables) {
    const docs = db.tableDocs[table.name];
    if (!docs)
      throw new Error(`Table ${table.name} is missing from packages/db/src/schema/docs.ts`);

    const fkByColumn = new Map<string, string>();
    for (const fk of table.foreignKeys) {
      const ref = fk.reference();
      const target = getTableConfig(ref.foreignTable).name;
      for (const column of ref.columns) {
        fkByColumn.set(column.name, `${target}.${ref.foreignColumns[0]?.name ?? 'id'}`);
      }
      relations.push(
        `  ${target} ||--o{ ${table.name} : "${ref.columns.map((c) => c.name).join(', ')}"`,
      );
    }

    const rows = table.columns.map((column) => {
      const description = docs.columns[column.name];
      if (!description) {
        throw new Error(
          `Column ${table.name}.${column.name} is missing from packages/db/src/schema/docs.ts`,
        );
      }
      const notes = [
        column.primary ? 'primary key' : '',
        column.isUnique ? 'unique' : '',
        fkByColumn.has(column.name) ? `→ ${fkByColumn.get(column.name) ?? ''}` : '',
      ]
        .filter(Boolean)
        .join(', ');
      return `| \`${column.name}\` | ${column.getSQLType()} | ${column.notNull ? 'no' : 'yes'} | ${notes} | ${cell(description)} |`;
    });

    const extra = docs.columns;
    for (const name of Object.keys(extra)) {
      if (!table.columns.some((c) => c.name === name)) {
        throw new Error(`docs.ts documents ${table.name}.${name}, which does not exist`);
      }
    }

    const constraints = [
      ...table.indexes.map((index) => {
        const config = index.config;
        const columns = config.columns.map((c) => ('name' in c ? c.name : 'expression')).join(', ');
        return `- ${config.unique ? 'Unique index' : 'Index'} \`${config.name ?? ''}\` on (${columns})${config.method && config.method !== 'btree' ? ` using ${config.method}` : ''}`;
      }),
      ...table.checks.map((c) => `- Check \`${c.name}\``),
    ];

    entities.push(
      `  ${table.name} {`,
      ...table.columns.map(
        (c) =>
          `    ${c.getSQLType().replaceAll(' ', '_')} ${c.name}${c.primary ? ' PK' : fkByColumn.has(c.name) ? ' FK' : ''}`,
      ),
      '  }',
    );

    sections.push(
      `## \`${table.name}\``,
      '',
      docs.description,
      '',
      '| Column | Type | Nullable | Keys | Meaning |',
      '| --- | --- | --- | --- | --- |',
      ...rows,
      '',
      ...(constraints.length ? ['**Indexes and constraints**', '', ...constraints, ''] : []),
    );
  }

  return [
    '# Database reference',
    '',
    `<!-- ${GENERATED_NOTE} Sources: packages/db/src/schema/ -->`,
    '',
    '```mermaid',
    'erDiagram',
    ...relations,
    ...entities,
    '```',
    '',
    ...sections,
  ].join('\n');
}

const outputs: Record<string, string> = {
  'docs/generated/env.md': renderEnvMarkdown(),
  '.env.example': renderEnvExample(),
  'docs/generated/database.md': renderDatabaseMarkdown(),
};

const check = process.argv.includes('--check');
const stale: string[] = [];
for (const [path, content] of Object.entries(outputs)) {
  const fullPath = `${root}${path}`;
  if (check) {
    const current = await readFile(fullPath, 'utf8').catch(() => '');
    if (current !== content) stale.push(path);
  } else {
    await writeFile(fullPath, content);
    console.log(`wrote ${path}`);
  }
}
if (stale.length > 0) {
  console.error(`Out of date: ${stale.join(', ')}. Run \`pnpm docs\` and commit the result.`);
  process.exit(1);
}
if (check) console.log('Generated docs are up to date.');
